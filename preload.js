const { contextBridge, ipcRenderer, webUtils } = require('electron');

const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('xai', {
  settings: { get: inv('settings:get'), set: inv('settings:set') },
  setTitleBarTheme: inv('window:theme'),
  openData: inv('app:openData'),
  openExternal: inv('app:openExternal'),
  models: inv('ollama:models'),
  ps: inv('ollama:ps'),
  ping: inv('ollama:ping'),
  stream: inv('chat:stream'),
  stop: inv('chat:stop'),
  once: inv('chat:once'),
  onChunk: (fn) => ipcRenderer.on('chat:chunk', (_e, d) => fn(d)),
  onQuick: (fn) => ipcRenderer.on('app:quick', () => fn()),
  onTheme: (fn) => ipcRenderer.on('app:theme', () => fn()),
  conv: { list: inv('conv:list'), get: inv('conv:get'), save: inv('conv:save'), patch: inv('conv:patch'), del: inv('conv:delete'), search: inv('conv:search'), exportMd: inv('conv:export') },
  projects: { list: inv('projects:list'), save: inv('projects:save'), del: inv('projects:delete') },
  files: { pick: inv('files:pick'), read: inv('files:read'), saveText: inv('files:saveText') },
  runTool: inv('tools:run'),
  sysInfo: inv('sys:info'),
  mcp: { status: inv('mcp:status'), tools: inv('mcp:tools'), importable: inv('mcp:importable'), save: inv('mcp:save'), remove: inv('mcp:remove'), reconnect: inv('mcp:reconnect') },
  kb: { info: inv('kb:info'), addFiles: inv('kb:addFiles'), addFolder: inv('kb:addFolder'), addDocs: inv('kb:addDocs'), remove: inv('kb:remove'), drop: inv('kb:drop'), search: inv('kb:search') },
  memory: { list: inv('memory:list'), save: inv('memory:save') },
  voice: { available: inv('voice:available'), transcribe: inv('voice:transcribe'), speak: inv('voice:speak') },
  readImage: inv('img:read'),
  openImage: inv('img:open'),
  screenSources: inv('screen:sources'),
  pull: inv('ollama:pull'),
  deleteModel: inv('ollama:delete'),
  exportPdf: inv('export:pdf'),
  exportDoc: inv('export:doc'),
  lib: inv('lib:get'),
  quickSubmit: inv('quick:submit'),
  quickClose: inv('quick:close'),
  checkUpdate: inv('app:checkUpdate'),
  lan: inv('net:lan'),
  log: inv('log:write'),
  openLog: inv('log:open'),
  on: (ch, fn) => { if (['mcp:changed', 'memory:changed', 'kb:progress', 'pull:progress', 'app:quickSend', 'app:newchat'].includes(ch)) ipcRenderer.on(ch, (_e, d) => fn(d)); },
  pathFor: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
});
